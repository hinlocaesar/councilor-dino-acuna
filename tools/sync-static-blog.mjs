/**
 * Regenerates the blog section of the static build (assets/js/data.js) from the
 * same WordPress export the Umbraco build uses, so both builds list all 40
 * posts instead of 9 hand-written summaries.
 *
 *   node tools/sync-static-blog.mjs
 *
 * Only the `posts` array is rewritten; the `videos` array above it is
 * hand-maintained and is preserved.
 *
 * Static paths are relative to the page ("assets/img/posts/…") because the
 * static build can be opened straight off disk.
 */
import { readFileSync, writeFileSync } from "node:fs";

const posts = JSON.parse(readFileSync("cms/Seeding/wordpress-posts.json", "utf8"));
const target = "assets/js/data.js";
const src = readFileSync(target, "utf8");

// Keep everything up to (but not including) the posts array.
const marker = "  /* ---------------------------------------------------------------- posts --- */";
const cut = src.indexOf(marker);
if (cut < 0) {
  console.error(`Could not find the posts section in ${target}.`);
  process.exit(1);
}
const head = src.slice(0, cut);

const fmtDate = (iso) => {
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return "";
  const months = ["Jan","Feb","Mar","Apr","May","Jun","Jul","Aug","Sep","Oct","Nov","Dec"];
  return `${String(d.getUTCDate()).padStart(2, "0")} ${months[d.getUTCMonth()]} ${d.getUTCFullYear()}`;
};

const out = [];
out.push(marker);
out.push(`  /* ${posts.length} posts, generated by tools/sync-static-blog.mjs */`);
out.push("  posts: [");
for (const p of posts) {
  const img = p.featuredImage ? p.featuredImage.replace(/^\/img\//, "assets/img/") : "";
  out.push("    {");
  out.push(`      sortKey: ${JSON.stringify(p.id.toString().padStart(2, "0"))},`);
  out.push(`      title: ${JSON.stringify(p.title)},`);
  out.push(`      excerpt: ${JSON.stringify(p.excerpt)},`);
  out.push(`      tag: ${JSON.stringify(p.cardTag)},`);
  out.push(`      date: ${JSON.stringify(fmtDate(p.date))},`);
  out.push(`      url: ${JSON.stringify(p.url)},`);
  out.push(`      slug: ${JSON.stringify(p.slug)},`);
  out.push(`      featuredImage: ${JSON.stringify(img)}`);
  out.push("    },");
}
out.push("  ],");
out.push("};");
out.push("");

writeFileSync(target, head + out.join("\n"), "utf8");

console.log(`updated ${target}`);
console.log(`  posts             : ${posts.length}`);
console.log(`  with local thumb  : ${posts.filter((p) => p.featuredImage).length}`);
console.log(`  external images   : ${posts.filter((p) => /https?:/.test(p.featuredImage || "")).length}`);